ROOT = Path(__file__).resolve().parents[1]
PYTHON = ROOT / ".venv/bin/python"
COLCON = [str(PYTHON), "-c", "from colcon_core.command import main; raise SystemExit(main())"]
PACKAGES = [
    "gca_core",
    "gca_position",
    "gca_system_interfaces",
    "gca_client",
    "gca_ros",
    "system_coordinator",
    "gca_teleop",
    "system_bringup",
]


def source_manifest() -> dict[str, str]:
    """Hash build inputs without generated bytecode, overlays or legacy files."""
    extensions = {
        ".py",
        ".xml",
        ".yaml",
        ".json",
        ".msg",
        ".srv",
        ".action",
        ".txt",
        ".cfg",
        ".sh",
        ".toml",
    }
    paths = [ROOT / "requirements-dev.txt", ROOT / "pyproject.toml"]
    for base in (ROOT / "ros2_ws/src", ROOT / "tools", ROOT / "tests"):
        paths.extend(
            p
            for p in base.rglob("*")
            if p.is_file()
            and p.suffix in extensions
            and not any(part in ("__pycache__", ".pytest_cache") for part in p.parts)
        )
    return {
        str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)
    }


def clean_environment() -> dict:
    """Remove inherited overlays; load only the chosen underlay/install later."""
    env = dict(os.environ)
    for name in list(env):
        if name.startswith(("AMENT_", "COLCON_", "ROS_")) or name in (
            "PYTHONPATH",
            "LD_LIBRARY_PATH",
            "CMAKE_PREFIX_PATH",
        ):
            env.pop(name, None)
    env.update(
        PATH=f"{PYTHON.parent}:/usr/local/bin:/usr/bin:/bin",
        PYTHONNOUSERSITE="1",
        CMAKE_BUILD_PARALLEL_LEVEL="1",
        MAKEFLAGS="-j1",
        ROS_AUTOMATIC_DISCOVERY_RANGE="LOCALHOST",
        PYTHONDONTWRITEBYTECODE="1",
    )
    return env


def sourced(command: list[str], install: Path | None = None) -> list[str]:
    script = "set -eo pipefail\nsource /opt/ros/jazzy/setup.bash\n"
    if install is not None:
        script += "source " + shlex.quote(str(install / "local_setup.bash")) + "\n"
    script += "exec " + shlex.join(command)
    return ["bash", "--noprofile", "--norc", "-c", script]


@dataclass(frozen=True)
class ProcessIdentity:
    pid: int
    started: int
    parent: int
    group: int
    state: str


def process_identity(pid: int) -> ProcessIdentity | None:
    """Read bounded Linux identity; starttime prevents acting on a reused PID."""
    try:
        with Path(f"/proc/{pid}/stat").open("rb") as stream:
            raw = stream.read(4097)
        if len(raw) > 4096:
            return None
        fields = raw[raw.rfind(b")") + 2 :].split()
        return ProcessIdentity(
            pid, int(fields[19]), int(fields[1]), int(fields[2]), fields[0].decode()
        )
    except (OSError, ValueError, IndexError):
        return None


class OwnedProcesses:
    """Bounded cleanup of this command's descendants, including new sessions.

    A private inherited marker catches children orphaned between observations.
    No environment contents/marker are logged. Signals require a live recorded
    pid/starttime/group match; unrelated groups and our own group are excluded.
    """

    marker_name = "GCA_VERIFY_PROCESS_SCOPE"
    max_processes = 4096
    max_environment_bytes = 131072
    scan_budget_s = 0.2
    poll_s = 0.1

    def __init__(self, root: int, marker: str):
        self.marker = (self.marker_name + "=" + marker).encode()
        self.known: dict[tuple[int, int], ProcessIdentity] = {}
        self.inspected: set[tuple[int, int]] = set()
        self.errors: set[str] = set()
        initial = process_identity(root)
        if initial is not None:
            self.known[(initial.pid, initial.started)] = initial

    def capture(self) -> list[ProcessIdentity]:
        started = time.monotonic()
        snapshot = []
        snapshot_complete = True
        with os.scandir("/proc") as entries:
            for entry in entries:
                if not entry.name.isdigit():
                    continue
                if (
                    len(snapshot) >= self.max_processes
                    or time.monotonic() - started > self.scan_budget_s
                ):
                    self.errors.add("PROCESS_SCAN_CAPACITY_EXCEEDED")
                    snapshot_complete = False
                    break
                try:
                    if entry.stat().st_uid != os.getuid():
                        continue
                except OSError:
                    continue
                current = process_identity(int(entry.name))
                if current is not None:
                    snapshot.append(current)
        live = {(p.pid, p.started): p for p in snapshot if p.state != "Z"}
        # Keep only current identities so long runs cannot accumulate exited PIDs.
        self.known = {
            key: live.get(key, previous)
            for key, previous in self.known.items()
            if key in live or not snapshot_complete
        }
        self.inspected.intersection_update(live)
        for current in live.values():
            if time.monotonic() - started > self.scan_budget_s:
                self.errors.add("PROCESS_SCAN_CAPACITY_EXCEEDED")
                break
            key = (current.pid, current.started)
            if key in self.known or key in self.inspected:
                continue
            self.inspected.add(key)
            try:
                with Path(f"/proc/{current.pid}/environ").open("rb") as stream:
                    raw = stream.read(self.max_environment_bytes + 1)
                if len(raw) > self.max_environment_bytes:
                    self.errors.add("PROCESS_ENVIRONMENT_CAPACITY_EXCEEDED")
                elif self.marker in raw.split(b"\0"):
                    after = process_identity(current.pid)
                    if after and after.started == current.started:
                        self.known[key] = after
            except OSError:
                continue  # A process may finish between stat and environ reads.
        # Include descendants even when they intentionally replace their environment.
        owned_pids = {p.pid for p in self.known.values()}
        for _ in range(len(live)):
            added = False
            for key, current in live.items():
                if time.monotonic() - started > self.scan_budget_s:
                    self.errors.add("PROCESS_SCAN_CAPACITY_EXCEEDED")
                    return list(self.known.values())
                if key not in self.known and current.parent in owned_pids:
                    self.known[key] = current
                    owned_pids.add(current.pid)
                    added = True
            if not added:
                break
        return list(self.known.values())

    def cleanup(self, grace_s=2.0, kill_s=2.0) -> dict:
        initial = self.capture()
        result = {"found_live": len(initial), "signals": [], "remaining": [], "errors": []}
        for sig, duration in ((signal.SIGINT, grace_s), (signal.SIGKILL, kill_s)):
            deadline = time.monotonic() + duration
            sent = set()
            while True:
                alive = self.capture()
                if not alive:
                    break
                for member in alive:
                    current = process_identity(member.pid)
                    if not current or current.started != member.started or current.state == "Z":
                        continue
                    if current.group == os.getpgrp():
                        self.errors.add("OWNED_CHILD_JOINED_VERIFIER_GROUP")
                        continue
                    if current.group in sent:
                        continue
                    try:
                        os.killpg(current.group, sig)
                        sent.add(current.group)
                        result["signals"].append(
                            {
                                "pid": current.pid,
                                "starttime": current.started,
                                "group": current.group,
                                "signal": sig.name,
                            }
                        )
                    except ProcessLookupError:
                        pass
                    except OSError as exc:
                        self.errors.add("PROCESS_SIGNAL_FAILED:" + type(exc).__name__)
                if time.monotonic() >= deadline:
                    break
                time.sleep(min(self.poll_s, max(0, deadline - time.monotonic())))
            if not alive:
                break
        result["remaining"] = [p.pid for p in self.capture()]
        result["errors"] = sorted(self.errors)
        result["complete"] = not result["remaining"] and not result["errors"]
        return result


class Verification:
    def __init__(self, output: Path):
        self.output = output
        self.output.mkdir(parents=True, exist_ok=True)
        self.report = {
            "started_utc": datetime.now(timezone.utc).isoformat(),
            "python": sys.version,
            "commands": [],
            "passed": False,
            "physical_hil": {"H01": "NOT_RUN", "H02": "NOT_RUN", "H03": "NOT_RUN"},
        }

    def save(self):
        (self.output / "report.json").write_text(json.dumps(self.report, indent=2) + "\n")

    def run(
        self,
        label: str,
        command: list[str],
        cwd: Path = ROOT,
        install: Path | None = None,
        deadline_s: float = 1200,
    ) -> None:
        print(f"[{label}] {shlex.join(command)}", flush=True)
        start = time.monotonic()
        log = self.output / (label + ".log")
        entry = {
            "label": label,
            "command": command,
            "cwd": str(cwd),
            "install": str(install) if install else None,
            "log": str(log),
        }
        marker = secrets.token_hex(24)
        environment = clean_environment()
        environment[OwnedProcesses.marker_name] = marker
        with log.open("w") as stream:
            process = subprocess.Popen(
                sourced(command, install),
                cwd=cwd,
                env=environment,
                stdout=stream,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
            owned = OwnedProcesses(process.pid, marker)
            try:
                deadline = time.monotonic() + deadline_s
                while process.poll() is None:
                    owned.capture()
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        raise subprocess.TimeoutExpired(command, deadline_s)
                    try:
                        process.wait(timeout=min(owned.poll_s, remaining))
                    except subprocess.TimeoutExpired:
                        pass
            except subprocess.TimeoutExpired:
                entry["timeout"] = True
            except BaseException:
                entry["interrupted"] = True
                raise
            finally:
                # Capture before signalling so independently launched ROS groups
                # cannot escape when their test parent exits. A private inherited
                # marker also finds children already adopted by PID 1.
                entry["cleanup"] = owned.cleanup()
                try:
                    process.wait(timeout=0.2)
                except subprocess.TimeoutExpired:
                    entry["cleanup"]["complete"] = False
                entry["exit_code"] = process.returncode
                entry["wall_s"] = time.monotonic() - start
                self.report["commands"].append(entry)
                self.save()
        if (
            entry["exit_code"] != 0
            or entry.get("timeout")
            or not entry["cleanup"]["complete"]
            or entry["cleanup"]["found_live"]
        ):
            print(log.read_text()[-12000:], flush=True)
            raise RuntimeError(f"{label} failed; see {log}")
        print(f"[{label}] PASS ({entry['wall_s']:.1f} s)", flush=True)


def build_command(build: Path, install: Path, log: Path) -> list[str]:
    return [
        *COLCON,
        "--log-base",
        str(log),
        "build",
        "--base-paths",
        str(ROOT / "ros2_ws/src"),
        "--build-base",
        str(build),
        "--install-base",
        str(install),
        "--executor",
        "sequential",
        "--packages-select",
        *PACKAGES,
        "--event-handlers",
        "console_direct+",
        "--cmake-args",
        "-DCMAKE_BUILD_TYPE=RelWithDebInfo",
        f"-DPython3_EXECUTABLE={PYTHON}",
        f"-DPYTHON_EXECUTABLE={PYTHON}",
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "artifacts/verification/latest")
    args = parser.parse_args()
    verification = Verification(args.output.resolve())
    lock = (ROOT / "artifacts/.verification.lock").open("a")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        print("Another verification owns this workspace; no concurrent build was started.")
        lock.close()
        return 2
    workspace = ROOT / "ros2_ws"
    install = workspace / "install"
    sources = source_manifest()
    (verification.output / "sources.json").write_text(json.dumps(sources, indent=2) + "\n")
    verification.report["source_manifest_sha256"] = hashlib.sha256(
        json.dumps(sources, sort_keys=True).encode()
    ).hexdigest()
    try:
        verification.run(
            "static", [str(PYTHON), "-m", "ruff", "check", "ros2_ws/src", "tools", "tests"]
        )
        verification.run(
            "format",
            [str(PYTHON), "-m", "ruff", "format", "--check", "ros2_ws/src", "tools", "tests"],
        )
        verification.run(
            "build", build_command(workspace / "build", install, workspace / "log"), workspace
        )
        test_dirs = [
            str(ROOT / "tests"),
            *(
                str(workspace / "src" / p / "test")
                for p in (
                    "gca_core",
                    "gca_position",
                    "gca_client",
                    "gca_ros",
                    "system_coordinator",
                    "system_bringup",
                    "gca_teleop",
                )
            ),
        ]
        junit = verification.output / "pytest.xml"
        with tempfile.TemporaryDirectory(prefix="gca-installed-tests-") as outside:
            verification.run(
                "pytest",
                [str(PYTHON), "-m", "pytest", "-q", *test_dirs, f"--junitxml={junit}"],
                Path(outside),
                install,
                600,
            )
        suites = ET.parse(junit).getroot()
        counts = {
            name: sum(int(s.attrib.get(name, 0)) for s in suites.iter("testsuite"))
            for name in ("tests", "failures", "errors", "skipped")
        }
        verification.report["pytest"] = counts
        if counts["tests"] == 0 or any(counts[n] for n in ("failures", "errors", "skipped")):
            raise RuntimeError(f"Required software tests must all run: {counts}")
        verification.run(
            "colcon-test",
            [
                *COLCON,
                "--log-base",
                str(workspace / "log"),
                "test",
                "--build-base",
                str(workspace / "build"),
                "--executor",
                "sequential",
                "--packages-select",
                *PACKAGES,
            ],
            workspace,
            install,
            600,
        )
        verification.run(
            "colcon-results",
            [*COLCON, "test-result", "--test-result-base", str(workspace / "build"), "--verbose"],
            workspace,
            install,
        )
        # Unique ordinary installation: no symlink or previous build products can
        # satisfy package/resource imports. Retained as reproducibility evidence.
        clean = (
            ROOT
            / "artifacts/clean-install"
            / datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        )
        clean.mkdir(parents=True)
        # Rotate only directories explicitly marked by this tool. Unknown/user
        # directories are never traversed for deletion. Keep the last two
        # completed installations plus the current in-progress one.
        owned = []
        for candidate in clean.parent.iterdir():
            marker = candidate / ".gca-generated.json"
            if candidate.is_symlink() or not candidate.is_dir() or not marker.is_file():
                continue
            try:
                ownership = json.loads(marker.read_text())
            except (OSError, ValueError):
                continue
            if ownership == {"generator": "tools/verify_software.py", "project": str(ROOT)}:
                owned.append(candidate)
        for expired in sorted(owned)[:-2]:
            shutil.rmtree(expired)
        (clean / ".gca-generated.json").write_text(
            json.dumps({"generator": "tools/verify_software.py", "project": str(ROOT)})
        )
        clean_install = clean / "install"
        verification.run(
            "ordinary-install", build_command(clean / "build", clean_install, clean / "log"), clean
        )
        with tempfile.TemporaryDirectory(prefix="gca-clean-smoke-") as outside:
            verification.run(
                "installed-resources",
                [str(PYTHON), str(ROOT / "tools/installed_smoke.py")],
                Path(outside),
                clean_install,
            )
            verification.run(
                "simulation",
                [
                    "env",
                    f"GCA_INSTALL_ROOT={clean_install}",
                    "bash",
                    str(ROOT / "tools/run_simulation_suite.sh"),
                    "--output",
                    str(ROOT / "artifacts/simulation/latest"),
                ],
                Path(outside),
                clean_install,
                600,
            )
            verification.run(
                "teleop",
                [
                    "env",
                    f"GCA_INSTALL_ROOT={clean_install}",
                    "bash",
                    str(ROOT / "tools/run_teleop_suite.sh"),
                    "--output",
                    str(ROOT / "artifacts/teleop/latest"),
                ],
                Path(outside),
                clean_install,
                900,
            )
        verification.report["ordinary_install"] = str(clean_install)
        if source_manifest() != sources:
            raise RuntimeError(
                "Source files changed during verification; rebuild the final snapshot"
            )
        verification.report["passed"] = True
    except Exception as exc:
        verification.report["error"] = f"{type(exc).__name__}: {exc}"
        print(verification.report["error"], flush=True)
    finally:
        verification.report["finished_utc"] = datetime.now(timezone.utc).isoformat()
        verification.save()
        lock.close()
    print(f"Verification evidence: {verification.output / 'report.json'}", flush=True)
    return 0 if verification.report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
