"""Device methods are called only by their owning I/O task.

Deadlines are absolute local monotonic nanoseconds. An adapter must bound its
underlying I/O; wrapping an unbounded call in an outer future is insufficient.
"""

from typing import Protocol

from .models import (
    DeviceIdentity,
    EncoderSample,
    PulseAbort,
    PulseCompletion,
    PulseSegment,
    ServoSample,
)


class ServoPort(Protocol):
    def open(self) -> DeviceIdentity: ...
    def configure(self) -> None: ...
    def enable(self, enabled: bool) -> None: ...
    def write_velocity(self, velocity_mm_s: float, deadline_ns: int) -> float: ...
    def read_state(self, deadline_ns: int) -> ServoSample: ...
    def stop(self, deadline_ns: int) -> None: ...
    def close(self) -> None: ...


class EncoderPort(Protocol):
    def open(self) -> DeviceIdentity: ...
    def read(self, deadline_ns: int) -> EncoderSample: ...
    def close(self) -> None: ...


class PulseEngine(Protocol):
    def open(self) -> DeviceIdentity: ...
    def submit(self, segment: PulseSegment) -> None: ...
    def poll(self) -> list[PulseCompletion]: ...
    def abort(self) -> PulseAbort: ...
    def is_idle(self) -> bool: ...
    def close(self) -> None: ...
